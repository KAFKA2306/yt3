import { describe, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import path from "node:path";
import fs from "fs-extra";
import {
	getByosanVisualSystem,
	getKafkaVisualSystem,
} from "../src/domain/design/kafka_visual_system.js";
import {
	BYOSAN_DESIGN_PATHS,
	buildByosanVideoSystem,
	loadByosanTokenMap,
	loadDesignTokens,
} from "../src/scripts/sync_video_design.js";

type Leaf = [pointer: string, value: unknown];

function leaves(node: unknown, prefix = ""): Leaf[] {
	if (node === null || typeof node !== "object") return [[prefix, node]];
	return Object.entries(node).flatMap(([key, child]) =>
		leaves(child, prefix ? `${prefix}.${key}` : key),
	);
}

function isRadiusPointer(pointer: string): boolean {
	return pointer
		.split(".")
		.some((segment) => segment === "radius" || segment.endsWith("_radius"));
}

describe("byosan video design conformance", () => {
	test("pins the design token file to its recorded hash", () => {
		const source = fs.readJsonSync("config/design/design_source.json");
		const tokenFile = path.join("config/design", path.basename(source.file));
		expect(
			createHash("sha256").update(fs.readFileSync(tokenFile)).digest("hex"),
		).toBe(source.sha256);
	});

	test("generated byosan design equals the token map applied to the shared base and pinned tokens", () => {
		const output = fs.readJsonSync(BYOSAN_DESIGN_PATHS.output);
		const expected = buildByosanVideoSystem(
			fs.readJsonSync(BYOSAN_DESIGN_PATHS.base),
			loadByosanTokenMap(),
			loadDesignTokens(),
		);
		expect(output).toEqual(expected);
	});

	test("every hex color and radius in the byosan design is mapped or an explicit exception", () => {
		const map = loadByosanTokenMap();
		const mapped = new Set([
			...Object.keys(map.targets),
			...Object.keys(map.exceptions),
		]);
		const unmapped = leaves(fs.readJsonSync(BYOSAN_DESIGN_PATHS.output))
			.filter(
				([pointer, value]) =>
					(typeof value === "string" && /^#[0-9A-F]{6}$/.test(value)) ||
					(typeof value === "number" && isRadiusPointer(pointer)),
			)
			.map(([pointer]) => pointer)
			.filter((pointer) => !mapped.has(pointer));
		expect(unmapped).toEqual([]);
	});

	test("byosan design loads through the design schema and geometry checks", () => {
		expect(getByosanVisualSystem().colors.background).toBe("#F7F5EF");
	});

	test("byosan renderer draws flat single-color scenes without gradients, glows or shadows", () => {
		const source = fs.readFileSync(
			"src/scripts/produce_byosan_feature.ts",
			"utf8",
		);
		expect(source).not.toMatch(
			/Gradient|<filter|feDropShadow|fill="url\(|glow/i,
		);
	});
});

describe("humanity shared design is pinned to HEAD", () => {
	test("getKafkaVisualSystem reads the unchanged shared design file", () => {
		const head = fs.readJsonSync(
			"tests/fixtures/design/kafka_visual_system_v1.head.json",
		);
		expect(getKafkaVisualSystem()).toEqual(head);
	});

	test("shared design file bytes equal the pinned HEAD fixture", () => {
		expect(
			createHash("sha256")
				.update(fs.readFileSync("config/design/kafka_visual_system_v1.json"))
				.digest("hex"),
		).toBe(
			createHash("sha256")
				.update(
					fs.readFileSync(
						"tests/fixtures/design/kafka_visual_system_v1.head.json",
					),
				)
				.digest("hex"),
		);
	});
});
